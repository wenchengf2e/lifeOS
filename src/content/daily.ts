import type { CheckinData } from "../../shared/types";

/**
 * 每日练习里的一个问题。
 *
 * 三个模块的写法不一样（事前计划 / 晚间日记 / 事后复盘），但渲染结构是同一套：
 * 标题 + 可选的追问 + 可选的标签 + 输入框。所以共用一个类型，
 * 页面只写一个 renderField，不用为每个模块各写一遍。
 */
export type DailyField = {
  key: keyof CheckinData;
  /** 问题标题。模块标题已经说明主题时（比如今日行动）可以省略。 */
  title?: string;
  /** 主问题，始终显示 */
  prompt?: string;
  /** 追问清单，折叠在「展开追问」里，想深挖的时候再打开 */
  detail?: string;
  /** 标题下方的小字注释 */
  tag?: string;
  placeholder: string;
  rows?: number;
};

export type DailyModule = {
  id: string;
  /** 模块上方的序号 + 时段 */
  kicker: string;
  title: string;
  description: string;
  fields: DailyField[];
  /** 模块末尾的可选补充项，视觉上弱一档 */
  tail?: DailyField;
};

